def wazuh_level_to_severity(level):
    """Map a Wazuh rule level (0-16) to a CyberGuard severity."""
    level = int(level or 0)
    if level >= 15:
        return 'critical'
    if level >= 12:
        return 'high'
    if level >= 7:
        return 'medium'
    return 'low'


def score_to_level(score):
    """Map a 1-25 likelihood x impact score to a risk level."""
    if score > 16:
        return 'critical'
    if score > 9:
        return 'high'
    if score > 4:
        return 'medium'
    return 'low'


def cvss_to_severity(score):
    score = float(score or 0.0)
    if score >= 9.0:
        return 'critical'
    if score >= 7.0:
        return 'high'
    if score >= 4.0:
        return 'medium'
    return 'low'


def notify_action(title, message, kind='success', sticky=False, next_action=None):
    """Build a client notification action."""
    params = {'title': title, 'message': message, 'type': kind, 'sticky': sticky}
    if next_action:
        params['next'] = next_action
    return {'type': 'ir.actions.client', 'tag': 'display_notification', 'params': params}


# ---------------------------------------------------------------------------
# System-generated records
#
# Alerts, indicators, ATT&CK techniques, vulnerabilities, AI analyses, response
# recommendations and notifications come from Wazuh, ThreatFox, NVD, the AI
# engine or the automation rules. People may work them (acknowledge, assign,
# resolve, add notes) but may not type them in, rewrite their source data or
# delete them. The guard below enforces that on the server, so it also covers
# imports, the JSON-RPC API and anything a modified view might allow.
# ---------------------------------------------------------------------------
def system_write(method):
    """Run an import / sync / generation method as the system.

    Wrap every method that legitimately creates or rewrites system-generated
    records (a sync button, a cron, an AI analysis). The logged-in user is kept
    (``env.uid`` is unchanged) but the guard and the ACLs are lifted for the call.
    """
    @functools.wraps(method)
    def wrapper(self, *args, **kwargs):
        return method(self.sudo(), *args, **kwargs)
    return wrapper


class CgSystemRecord(models.AbstractModel):
    _name = 'cg.system.record'
    _description = 'Guard for system-generated records'

    # Source-data fields nobody may edit by hand; workflow fields stay editable.
    _cg_locked_fields = ()
    _cg_lock_create = True
    _cg_lock_unlink = True

    def _cg_is_system(self):
        return bool(self.env.su or self.env.context.get('install_mode')
                    or self.env.context.get('cg_system_write'))

    @api.model_create_multi
    def create(self, vals_list):
        if self._cg_lock_create and not self._cg_is_system():
            raise UserError("%s records are generated by the system and cannot be created manually."
                            % self._description)
        return super().create(vals_list)

    def write(self, vals):
        if self._cg_locked_fields and not self._cg_is_system():
            blocked = sorted(set(vals) & set(self._cg_locked_fields))
            if blocked:
                labels = ', '.join(self._fields[name].string or name for name in blocked)
                raise UserError("%s data comes from the source system and cannot be edited manually (%s)."
                                % (self._description, labels))
        return super().write(vals)

    def unlink(self):
        if self._cg_lock_unlink and not self._cg_is_system():
            raise UserError("%s records are part of the security record and cannot be deleted."
                            % self._description)
        return super().unlink()

    @api.model
    def fields_get(self, allfields=None, attributes=None):
        """Show source-data fields as read-only in every form and list."""
        result = super().fields_get(allfields, attributes)
        if not self._cg_is_system():
            for name in self._cg_locked_fields:
                if name in result:
                    result[name]['readonly'] = True
        return result
